#!/usr/bin/env python3
"""
Evaluation harness (Phase A) — run the frozen eval sets through a model and score.

Establishes the per-capability scoreboard used to (a) baseline an un-tuned model and
(b) measure the effect of SFT/DPO. Model-agnostic via runners.py; metrics per TDD §9
live in metrics.py. Emits a Markdown + JSON scorecard.

Usage:
    # baseline floor (no model needed):
    python src/eval/run_eval.py --runner null --md doc/reports/eval-baseline.md
    # against a self-hosted model:
    python src/eval/run_eval.py --runner hf:Qwen/Qwen3-8B --limit 20
    python src/eval/run_eval.py --runner openai:http://localhost:8000:qwen3-8b
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from runners import get_runner            # noqa: E402
from metrics import METRICS               # noqa: E402

EVAL_DIR = Path("data/eval")
EVAL_SETS = {
    "C1": EVAL_DIR / "eval_c1_qa.jsonl",
    "C2": EVAL_DIR / "eval_c2_gen.jsonl",
    "C3": EVAL_DIR / "eval_c3_defects.jsonl",
    "C4": EVAL_DIR / "eval_c4_narrate.jsonl",
    "C6": EVAL_DIR / "eval_c6_automation.jsonl",
    "C7": EVAL_DIR / "eval_c7_compliance.jsonl",
}
CAP_NAME = {"C1": "Q&A / Tutor", "C2": "NL→BPMN generation", "C3": "Review / defects",
            "C4": "Narration", "C6": "Automation detection", "C7": "Compliance check"}


def _rows(path: Path, limit=None):
    out = []
    if not path.exists():
        return out
    for line in path.open(encoding="utf-8"):
        if line.strip():
            out.append(json.loads(line))
            if limit and len(out) >= limit:
                break
    return out


def _prompt(row):
    instr = row.get("instruction", "")
    inp = row.get("input", "")
    return f"{instr}\n\n{inp}" if isinstance(inp, str) and inp.strip() else instr


def run(runner, limit=None):
    scoreboard = {}
    for cap, path in EVAL_SETS.items():
        desc, metric_fn = METRICS[cap]
        rows = _rows(path, limit)
        if not rows:
            scoreboard[cap] = {"n": 0, "score": None, "metric": desc, "detail": {}}
            continue
        scores, extra = [], []
        for row in rows:
            pred = runner.generate(_prompt(row))
            res = metric_fn(row, pred)
            scores.append(res["score"])
            extra.append(res)
        agg = {"n": len(rows), "score": round(sum(scores) / len(scores), 3), "metric": desc}
        # capability-specific rollups
        if cap == "C2":
            agg["xsd_valid_rate"] = round(sum(1 for e in extra if e.get("xsd_valid")) / len(extra), 3)
        if cap == "C3":
            defects = [e for e in extra if e.get("kind") == "defect"]
            cleans = [e for e in extra if e.get("kind") == "clean"]
            agg["defect_recall"] = round(sum(1 for e in defects if e.get("detected")) / len(defects), 3) if defects else None
            agg["false_positive_rate"] = round(sum(1 for e in cleans if e.get("false_positive")) / len(cleans), 3) if cleans else None
        scoreboard[cap] = agg
    return scoreboard


def render(scoreboard, runner_name, limit):
    L = ["# Evaluation Scorecard (Phase A baseline)\n"]
    L.append("_Generated by `src/eval/run_eval.py` — metrics per TDD §9. "
             "Run against the un-tuned model this is the BASELINE; re-run after SFT/DPO to measure lift._\n")
    L.append(f"- **Model / runner:** `{runner_name}`")
    L.append(f"- **Rows per set:** {'all' if not limit else limit}\n")
    L.append("| Cap | Capability | n | Score | Metric |")
    L.append("|-----|-----------|:-:|:-----:|--------|")
    for cap, a in scoreboard.items():
        s = "—" if a["score"] is None else f"{a['score']:.3f}"
        L.append(f"| {cap} | {CAP_NAME[cap]} | {a['n']} | {s} | {a['metric']} |")
    L.append("")
    # objective rollups
    c2, c3 = scoreboard.get("C2", {}), scoreboard.get("C3", {})
    if c2.get("xsd_valid_rate") is not None:
        L.append(f"- **C2 XSD-valid rate:** {c2['xsd_valid_rate']:.1%}")
    if c3.get("defect_recall") is not None:
        L.append(f"- **C3 defect recall:** {c3['defect_recall']:.1%} · "
                 f"**false-positive rate:** {c3['false_positive_rate']:.1%}")
    L.append("\n> Scores of 0.0 for the `null` runner are the expected floor. "
             "C1/C4/C6 use a lexical proxy; wire an LLM-judge / RAGAS for the production metric (TDD §9).")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description="Run the BPMN eval sets through a model (Phase A).")
    ap.add_argument("--runner", default="null", help="null | hf:<id> | openai:<url>:<model>")
    ap.add_argument("--limit", type=int, default=None, help="Rows per eval set (for quick runs)")
    ap.add_argument("--md", type=Path, default=Path("doc/reports/eval-baseline.md"))
    ap.add_argument("--json", dest="json_out", type=Path, default=None)
    args = ap.parse_args()

    runner = get_runner(args.runner)
    scoreboard = run(runner, args.limit)
    report = render(scoreboard, runner.name, args.limit)

    args.md.parent.mkdir(parents=True, exist_ok=True)
    args.md.write_text(report, encoding="utf-8")
    if args.json_out:
        args.json_out.write_text(json.dumps({"runner": runner.name, "scoreboard": scoreboard}, indent=2),
                                 encoding="utf-8")
    try:
        if hasattr(sys.stdout, "reconfigure"):
            sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    print(report)
    print(f"[written] {args.md}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
